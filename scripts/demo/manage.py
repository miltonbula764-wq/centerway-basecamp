"""Private single-origin Codespaces demo. No remote DB input, production env or deployment."""
import argparse
import base64
import fcntl
import hashlib
import hmac
import json
import os
from pathlib import Path
import re
import signal
import subprocess
import sys
import time
import urllib.request

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'scripts/mvp'))
from disposable import DEMO_VOLUME, require_local_database
from runtime import clean_env, provision, stage_source, CONTAINERS
STATE = ROOT / '.centerway-demo'
APP = STATE / 'app'


def origin():
    if os.environ.get('CODESPACES') == 'true':
        name = os.environ.get('CODESPACE_NAME', '')
        domain = os.environ.get('GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN', 'app.github.dev')
        if not re.fullmatch(r'[a-z0-9-]+', name) or domain != 'app.github.dev':
            raise RuntimeError('Unsupported Codespaces hostname; refusing to guess an origin.')
        # Codespaces defaults private; explicitly enforce it before starting any listener.
        subprocess.run(['gh', 'codespace', 'ports', 'visibility', '8080:private', '--codespace', name], check=True)
        ports = json.loads(subprocess.check_output(['gh','codespace','ports','--codespace',name,'--json','sourcePort,visibility'],text=True))
        if not any(str(p['sourcePort'])=='8080' and p['visibility']=='private' for p in ports):
            raise RuntimeError('Porta 8080 não confirmada como privada; arranque bloqueado.')
        if any(str(p['sourcePort']) in ('5432','9999','54321','54322','5173') for p in ports):
            raise RuntimeError('Remova o encaminhamento das portas internas no separador Ports antes de iniciar.')
        return f'https://{name}-8080.{domain}'
    if os.environ.get('CW_DEMO_TLS_TEST') == '1':
        return 'https://demo.centerway.test:8443'
    raise RuntimeError('Codespaces required. Local TLS validation uses explicit CW_DEMO_TLS_TEST=1; this is not remote verification.')


def env_for_demo(public_origin):
    env = clean_env()
    env.update(CW_CODESPACES_DEMO='1', CW_DEMO_ORIGIN=public_origin)
    return env


def check_containers():
    env = env_for_demo('unused')
    saved = {k: os.environ.get(k) for k in ['PGHOST', 'PGDATABASE', 'CW_CODESPACES_DEMO']}
    try:
        os.environ.update({k: env[k] for k in saved})
        info = require_local_database()
    finally:
        for k, v in saved.items():
            if v is None: os.environ.pop(k, None)
            else: os.environ[k] = v
    if info['Config']['Labels'].get('centerway.disposable') != 'codespaces':
        raise RuntimeError('Refuse to manage another local stack.')
    for name in CONTAINERS[1:]:
        info = json.loads(subprocess.check_output(['docker', 'inspect', name]))[0]
        if info['Config'].get('Labels', {}).get('centerway.disposable') != 'true' or info['Config'].get('Labels', {}).get('centerway.demo') != 'codespaces':
            raise RuntimeError('Refuse to manage unlabelled container ' + name)
        bindings = info['HostConfig'].get('PortBindings', {})
        if any(p['HostIp'] != '127.0.0.1' for values in bindings.values() for p in values):
            raise RuntimeError('Internal service has a non-loopback binding.')


def refresh_config(public_origin):
    # These are secrets GENERATED by this disposable stack, never hosted/injected credentials.
    auth_file = APP / 'e2e/private/auth.env'
    values = dict(line.split('=', 1) for line in auth_file.read_text().splitlines())
    values.update(GOTRUE_SITE_URL=public_origin, GOTRUE_URI_ALLOW_LIST=public_origin+'/**', API_EXTERNAL_URL=public_origin+'/auth/v1', GOTRUE_DISABLE_SIGNUP='true')
    auth_file.write_text(''.join(k+'='+v+'\n' for k,v in values.items()))
    auth_file.chmod(0o600)
    b64 = lambda value: base64.urlsafe_b64encode(value).decode().rstrip('=')
    unsigned = b64(b'{"alg":"HS256","typ":"JWT"}') + '.' + b64(json.dumps({'role':'anon','iss':'supabase','iat':int(time.time()),'exp':int(time.time())+604800}).encode())
    anon = unsigned + '.' + b64(hmac.new(values['GOTRUE_JWT_SECRET'].encode(), unsigned.encode(), hashlib.sha256).digest())
    (APP / '.env.local').write_text('VITE_SUPABASE_URL='+public_origin+'\nVITE_SUPABASE_PUBLISHABLE_KEY='+anon+'\n')
    (APP / 'e2e/private/public.json').write_text(json.dumps({'url':'http://127.0.0.1:54321','anon':anon}))
    # Recreate only this own auth container to apply redirect origin / disable signup. DB and users remain intact.
    subprocess.run(['docker','rm','-f','cw-auth'],check=True,stdout=subprocess.DEVNULL)
    subprocess.run(['docker','run','-d','--name','cw-auth','--label','centerway.disposable=true','--label','centerway.demo=codespaces','--network','cw-e2e','-p','127.0.0.1:9999:9999','--env-file',str(auth_file),'supabase/gotrue:v2.177.0'],check=True,stdout=subprocess.DEVNULL)
    subprocess.run(['docker','restart','cw-gateway'],check=True,stdout=subprocess.DEVNULL)
    return anon


def stop_frontend():
    pid_file = STATE / 'frontend.pid'
    if not pid_file.exists(): return
    pid = int(pid_file.read_text())
    try:
        # Never signal a reused PID belonging to another app.
        cwd = Path(f'/proc/{pid}/cwd').resolve()
        command = Path(f'/proc/{pid}/cmdline').read_bytes()
        if cwd != APP or b'scripts/demo/vite.config.ts' not in command:
            raise RuntimeError('Refuse to signal unrelated process.')
        os.killpg(pid, signal.SIGTERM)
    except FileNotFoundError: pass
    except ProcessLookupError: pass
    pid_file.unlink(missing_ok=True)


def start(background):
    stop_frontend()
    public_origin = origin()
    ready = STATE / 'ready.json'
    if not ready.exists():
        if APP.exists(): raise RuntimeError('Incomplete provisioning. Inspect demo.log; explicit reset required, no automatic data deletion.')
        stage_source(ROOT, APP)
        provision(APP, persistent=True, origin=public_origin)
        ready.write_text(json.dumps({'commit':subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),'database':'own-disposable-volume'}))
    check_containers()
    subprocess.run(['docker','start',*CONTAINERS],check=True,stdout=subprocess.DEVNULL)
    for _ in range(60):
        r = subprocess.run(['docker','exec','cw-mvp-db','pg_isready','-U','postgres','-d','cw_e2e'],capture_output=True)
        if r.returncode == 0: break
        time.sleep(1)
    else: raise RuntimeError('Own database did not resume.')
    # A stopped Codespace keeps the volume, users, goals and events. Never migrate/reseed on resume.
    check = subprocess.run(['docker','exec','cw-mvp-db','psql','-U','postgres','-d','cw_e2e','-Atc','SELECT count(*) FROM public.cw_operational_cases'],capture_output=True)
    if check.returncode: raise RuntimeError('Own database is not initialized; explicit reset required.')
    stop_frontend()
    anon = refresh_config(public_origin)
    env = env_for_demo(public_origin)
    env.update(SUPABASE_URL='http://127.0.0.1:54321', SUPABASE_PUBLISHABLE_KEY=anon)
    log = (STATE / 'frontend.log').open('a')
    process = subprocess.Popen(['bun','run','dev','--config','scripts/demo/vite.config.ts'],cwd=APP,env=env,stdout=log,stderr=subprocess.STDOUT,start_new_session=True)
    (STATE / 'frontend.pid').write_text(str(process.pid))
    for _ in range(60):
        if process.poll() is not None: raise RuntimeError('Frontend failed; inspect .centerway-demo/frontend.log')
        try:
            with urllib.request.urlopen('http://127.0.0.1:8080/auth/v1/health',timeout=2) as r:
                if r.status == 200: break
        except Exception: time.sleep(1)
    else: raise RuntimeError('Single-origin frontend/API not ready.')
    print('CENTERWAY · demonstração privada · apenas dados sintéticos',flush=True)
    print(public_origin+'/app/casos',flush=True)
    print('Credenciais locais: .centerway-demo/app/e2e/private/mvp-users.json',flush=True)
    print('Históricos retrospectivos são fictícios. PostgreSQL e APIs internas não são encaminhados.',flush=True)
    if not background:
        try: process.wait()
        except KeyboardInterrupt: stop_frontend()


def stop():
    if not (STATE/'ready.json').exists(): raise RuntimeError('No ready demo to stop.')
    check_containers()
    stop_frontend()
    subprocess.run(['docker','stop',*reversed(CONTAINERS)],check=True,stdout=subprocess.DEVNULL)
    print('Demo parada; dados preservados no volume próprio do Codespace.')


def reset():
    import shutil
    # Explicit operation only. Preflight ALL resources before removing anything.
    for name in CONTAINERS:
        r = subprocess.run(['docker','inspect',name],capture_output=True,text=True)
        if not r.returncode:
            label = json.loads(r.stdout)[0]['Config'].get('Labels',{}).get('centerway.disposable')
            if label != ('codespaces' if name=='cw-mvp-db' else 'true') or (name!='cw-mvp-db' and json.loads(r.stdout)[0]['Config'].get('Labels',{}).get('centerway.demo')!='codespaces'): raise RuntimeError('Refuse reset of another stack: '+name)
    r = subprocess.run(['docker','volume','inspect',DEMO_VOLUME],capture_output=True,text=True)
    if not r.returncode and json.loads(r.stdout)[0].get('Labels',{}).get('centerway.disposable') != 'codespaces': raise RuntimeError('Unlabelled volume')
    r = subprocess.run(['docker','network','inspect','cw-e2e'],capture_output=True,text=True)
    if not r.returncode and (json.loads(r.stdout)[0].get('Labels',{}).get('centerway.disposable') != 'true' or json.loads(r.stdout)[0].get('Labels',{}).get('centerway.demo') != 'codespaces'): raise RuntimeError('Unlabelled network')
    stop_frontend()
    for name in reversed(CONTAINERS): subprocess.run(['docker','rm','-f',name],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    subprocess.run(['docker','network','rm','cw-e2e'],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    subprocess.run(['docker','volume','rm',DEMO_VOLUME],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    shutil.rmtree(APP,ignore_errors=True)
    (STATE/'ready.json').unlink(missing_ok=True)
    print('Dados sintéticos desta demo eliminados. O próximo start cria uma stack nova de HEAD.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('command',choices=['start','stop','reset'])
    parser.add_argument('--background',action='store_true')
    args = parser.parse_args()
    STATE.mkdir(mode=0o700,exist_ok=True)
    with (STATE/'manage.lock').open('w') as lock:
        fcntl.flock(lock,fcntl.LOCK_EX)
        try:
            if args.command=='start': start(args.background)
            elif args.command=='stop': stop()
            else: reset()
        except (RuntimeError,AssertionError,subprocess.CalledProcessError) as e:
            print('Demo não iniciada/concluída: '+str(e),file=sys.stderr)
            raise SystemExit(1)
